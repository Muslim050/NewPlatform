/**
 * Палитра категорий для диаграмм: цвета раздаются по порядку слотов и не
 * повторяются — так «Телефон» не меняет цвет от того, что выше добавили
 * строку. Набор проверен на светлой подложке: попадание в диапазон
 * светлоты, порог цветности, различимость соседних пар при дальтонизме
 * (худшая пара — 4↔5, ΔE 6.1 при дейтеранопии). Такой ΔE допустим только
 * со вторым признаком, поэтому сектора всегда идут с подписями рядом
 * и разделены зазором.
 */
export const CHART_COLORS = [
  '#eda100', // жёлтый — фирменный
  '#2a78d6', // синий
  '#eb6834', // оранжевый
  '#1baf7a', // бирюзовый
  '#e87ba4', // розовый
  '#008300', // зелёный
  '#4a3aa7', // фиолетовый
  '#e34948', // красный
]

/** Серый для хвоста: девятая и дальше категории — «прочее». */
const REST_COLOR = '#8e8b98'

/**
 * Цвет сектора: свой из данных, иначе слот по порядку. Дальше восьмого
 * новый оттенок не выдумываем — такие доли читаются только по подписи.
 */
export const colorAt = (item, index) =>
  item?.color ?? CHART_COLORS[index] ?? REST_COLOR
