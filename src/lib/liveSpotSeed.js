function buildRows(prefix, channel, entries) {
  return entries.map(([date, time, tournament, event, views], index) => ({
    id: `${prefix}-${index + 1}`,
    date,
    time,
    tournament,
    event,
    channel,
    pre: "30",
    mid1: "15",
    mid2: "15",
    post: "30",
    views: String(views),
  }));
}

